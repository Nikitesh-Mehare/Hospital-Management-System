    /**
     * Handles the HTTP <code>POST</code> method.
     *
     * @param request servlet request
     * @param response servlet response
     * @throws ServletException if a servlet-specific error occurs
     * @throws IOException if an I/O error occurs
     */
    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        
        HttpSession session = request.getSession();
        int patient_id =(int) session.getAttribute("patient_id");
        int doctor_id = Integer.parseInt(request.getParameter("doctor_id"));
        String appointment_date =  request.getParameter("appointment_date");
        String appointment_time = request.getParameter("appointment_time");
        
        AppointmentDAO.bookAppointment(doctor_id, patient_id, appointment_date, appointment_time);
        
        response.sendRedirect("patient/view_appointment.jsp");

    }

